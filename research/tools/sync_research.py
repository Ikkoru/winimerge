#!/usr/bin/env python3
"""Copy /home/user/research into the research branch worktree, commit and push.

Images and binaries are left out (they are regenerated by harness/synth.py, re-downloaded from
testset/sources/MANIFEST.json, or rebuilt as described in harness/README.md); CSV results are
stored gzip-compressed. Usage: sync_research.py "commit message"
"""
import gzip
import os
import shutil
import subprocess
import sys

SRC = '/home/user/research'
REPO = '/home/user/winimerge-research'
DST = os.path.join(REPO, 'research')
BRANCH = 'claude/trusting-brown-3d75mh'
SKIP_DIRS = {'__pycache__', '.ipynb_checkpoints'}
SKIP_EXT = {'.so', '.o', '.a', '.npy', '.npz'}
IMAGE_EXT = {'.png', '.jpg', '.jpeg', '.webp', '.gif', '.bmp', '.tif', '.tiff'}
KEEP_IMAGES_UNDER = ('figures/', 'charts/')   # small, curated images that belong with the docs
SKIP_FILES = {'eyecheck/artifact.html', 'eyecheck2/artifact.html'}   # same pages as the index.html files
MAX_BYTES = 8 * 1024 * 1024


def wanted(rel):
    ext = os.path.splitext(rel)[1].lower()
    if ext in SKIP_EXT or rel in SKIP_FILES:
        return False
    if ext in IMAGE_EXT and not rel.startswith(KEEP_IMAGES_UNDER):
        return False
    return True


def main():
    msg = sys.argv[1] if len(sys.argv) > 1 else 'Update research notes'
    if os.path.isdir(DST):
        shutil.rmtree(DST)
    for root, dirs, files in os.walk(SRC):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            src = os.path.join(root, f)
            rel = os.path.relpath(src, SRC)
            if not wanted(rel) or os.path.islink(src):
                continue
            dst = os.path.join(DST, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            if rel.endswith('.csv'):
                with open(src, 'rb') as fi, gzip.open(dst + '.gz', 'wb', compresslevel=9) as fo:
                    shutil.copyfileobj(fi, fo)
            elif os.path.getsize(src) <= MAX_BYTES:
                shutil.copy2(src, dst)
    run = lambda *a: subprocess.run(['git', '-C', REPO, *a], check=True, capture_output=True, text=True)
    run('add', '-A', 'research')
    if subprocess.run(['git', '-C', REPO, 'diff', '--cached', '--quiet']).returncode == 0:
        print('nothing to commit')
        return
    run('commit', '-q', '-m', msg + '\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n'
        'Claude-Session: https://claude.ai/code/session_011DaoEzRioXAZckz9AW1kyX')
    for attempt in range(4):
        r = subprocess.run(['git', '-C', REPO, 'push', '-u', 'origin', BRANCH], capture_output=True, text=True)
        if r.returncode == 0:
            print('pushed', r.stderr.strip().splitlines()[-1] if r.stderr.strip() else '')
            return
        import time
        time.sleep(2 ** (attempt + 1))
    print('push failed:', r.stderr)
    sys.exit(1)


if __name__ == '__main__':
    main()
